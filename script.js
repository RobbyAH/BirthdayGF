// 9. FLOATING HEARTS & SPARKLES BACKGROUND CANVAS
// ============================================================================
let burstParticles = [];

function burstHearts(count = 30) {
  const symbols = ["❤️", "💖", "✨", "🌷", "💕", "🌸"];
  for (let i = 0; i < count; i++) {
    burstParticles.push({
      x: window.innerWidth * (0.2 + Math.random() * 0.6),
      y: window.innerHeight * (0.5 + Math.random() * 0.3),
      vx: (Math.random() - 0.5) * 7,
      vy: -(Math.random() * 6 + 3),
      size: 16 + Math.random() * 16,
      alpha: 1,
      symbol: symbols[Math.floor(Math.random() * symbols.length)]
    });
  }
}

function initCanvasParticles() {
  const canvas = document.getElementById("romantic-canvas");
  const ctx = canvas.getContext("2d");

  let width = (canvas.width = window.innerWidth);
  let height = (canvas.height = window.innerHeight);

  window.addEventListener("resize", () => {
    width = canvas.width = window.innerWidth;
    height = canvas.height = window.innerHeight;
  });

  const ambientHearts = Array.from({ length: 24 }, () => ({
    x: Math.random() * width,
    y: Math.random() * height,
    size: 10 + Math.random() * 12,
    speedY: 0.35 + Math.random() * 0.65,
    sway: Math.random() * Math.PI * 2,
    swaySpeed: 0.01 + Math.random() * 0.02,
    opacity: 0.18 + Math.random() * 0.35
  }));

  function draw() {
    ctx.clearRect(0, 0, width, height);

    // Ambient floating soft hearts
    ambientHearts.forEach((p) => {
      p.y -= p.speedY;
      p.sway += p.swaySpeed;
      p.x += Math.sin(p.sway) * 0.45;

      if (p.y < -30) {
        p.y = height + 20;
        p.x = Math.random() * width;
      }

      ctx.save();
      ctx.globalAlpha = p.opacity;
      ctx.font = `${p.size}px serif`;
      ctx.fillText("❤", p.x, p.y);
      ctx.restore();
    });

    // Interactive burst hearts
    for (let i = burstParticles.length - 1; i >= 0; i--) {
      const b = burstParticles[i];
      b.x += b.vx;
      b.y += b.vy;
      b.vy += 0.12; // gravity
      b.alpha -= 0.014;

      if (b.alpha <= 0) {
        burstParticles.splice(i, 1);
        continue;
      }

      ctx.save();
      ctx.globalAlpha = Math.max(0, b.alpha);
      ctx.font = `${b.size}px sans-serif`;
      ctx.fillText(b.symbol, b.x, b.y);
      ctx.restore();
    }

    requestAnimationFrame(draw);
  }

  draw();
}

