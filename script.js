// 3. COUNTDOWN MENUJU 10 NOVEMBER 2026
// ============================================================================
function initCountdown() {
  const targetTime = new Date(CONFIG.birthdayDateISO).getTime();
  const daysEl = document.getElementById("cd-days");
  const hoursEl = document.getElementById("cd-hours");
  const minsEl = document.getElementById("cd-minutes");
  const secsEl = document.getElementById("cd-seconds");
  const headingEl = document.getElementById("countdown-heading");
  const subEl = document.getElementById("countdown-sub");

  function updateTimer() {
    const now = new Date().getTime();
    const diff = targetTime - now;

    if (diff <= 0) {
      // Sudah memasuki tanggal 10 November 2026 atau setelahnya!
      daysEl.textContent = "10";
      hoursEl.textContent = "11";
      minsEl.textContent = "2026";
      secsEl.textContent = "❤️";
      headingEl.textContent = "🎉 HARI INI ADALAH HARI SPESIALMU! SELAMAT ULANG TAHUN SAYANGKU! 🎉";
      subEl.textContent = "Semoga tanggal 10 November 2026 ini menjadi awal dari sejuta kebahagiaan barumu.";
      return;
    }

    const d = Math.floor(diff / (1000 * 60 * 60 * 24));
    const h = Math.floor((diff % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
    const m = Math.floor((diff % (1000 * 60 * 60)) / (1000 * 60));
    const s = Math.floor((diff % (1000 * 60)) / 1000);

    daysEl.textContent = String(d).padStart(2, "0");
    hoursEl.textContent = String(h).padStart(2, "0");
    minsEl.textContent = String(m).padStart(2, "0");
    secsEl.textContent = String(s).padStart(2, "0");
  }

  updateTimer();
  setInterval(updateTimer, 1000);
}

