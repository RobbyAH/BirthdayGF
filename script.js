// 1. ROMANTIC MUSIC SYNTHESIZER (FALLBACK JIKA TIDAK ADA FILE MP3)
// ============================================================================
class RomanticMusicBox {
  constructor() {
    this.ctx = null;
    this.isPlaying = false;
    this.timer = null;
    this.noteIndex = 0;
    // Melodi romantis "Happy Birthday + Canon in D vibe" (frekuensi Hz)
    this.melody = [
      { f: 392.00, d: 0.45 }, // G4
      { f: 392.00, d: 0.45 }, // G4
      { f: 440.00, d: 0.85 }, // A4
      { f: 392.00, d: 0.85 }, // G4
      { f: 523.25, d: 0.85 }, // C5
      { f: 493.88, d: 1.40 }, // B4

      { f: 392.00, d: 0.45 }, // G4
      { f: 392.00, d: 0.45 }, // G4
      { f: 440.00, d: 0.85 }, // A4
      { f: 392.00, d: 0.85 }, // G4
      { f: 587.33, d: 0.85 }, // D5
      { f: 523.25, d: 1.40 }, // C5

      { f: 392.00, d: 0.45 }, // G4
      { f: 392.00, d: 0.45 }, // G4
      { f: 783.99, d: 0.85 }, // G5
      { f: 659.25, d: 0.85 }, // E5
      { f: 523.25, d: 0.85 }, // C5
      { f: 493.88, d: 0.85 }, // B4
      { f: 440.00, d: 1.30 }, // A4

      { f: 698.46, d: 0.45 }, // F5
      { f: 698.46, d: 0.45 }, // F5
      { f: 659.25, d: 0.85 }, // E5
      { f: 523.25, d: 0.85 }, // C5
      { f: 587.33, d: 0.85 }, // D5
      { f: 523.25, d: 1.60 }  // C5
    ];
  }

  playNote(freq, duration) {
    if (!this.ctx) return;
    const now = this.ctx.currentTime;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();

    // Suara lembut seperti music box
    osc.type = "sine";
    osc.frequency.setValueAtTime(freq, now);

    gain.gain.setValueAtTime(0.001, now);
    gain.gain.exponentialRampToValueAtTime(0.12, now + 0.04);
    gain.gain.exponentialRampToValueAtTime(0.0008, now + duration + 0.35);

    osc.connect(gain);
    gain.connect(this.ctx.destination);

    osc.start(now);
    osc.stop(now + duration + 0.4);
  }

  start() {
    if (this.isPlaying) return;
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!AudioCtx) return;
    if (!this.ctx) this.ctx = new AudioCtx();
    if (this.ctx.state === "suspended") this.ctx.resume();

    this.isPlaying = true;
    const step = () => {
      if (!this.isPlaying) return;
      const note = this.melody[this.noteIndex];
      this.playNote(note.f, note.d);
      this.noteIndex = (this.noteIndex + 1) % this.melody.length;
      this.timer = setTimeout(step, note.d * 1000);
    };
    step();
  }

  stop() {
    this.isPlaying = false;
    if (this.timer) clearTimeout(this.timer);
  }

  toggle() {
    if (this.isPlaying) {
      this.stop();
      return false;
    } else {
      this.start();
      return true;
    }
  }
}

const musicBox = new RomanticMusicBox();
let usingHtmlAudio = false;

function startRomanticMusic() {
  const audioEl = document.getElementById("bg-audio");
  const musicLabel = document.getElementById("music-label");
  const musicIcon = document.getElementById("music-icon");

  if (audioEl) {
    audioEl.volume = 0.6;
    const playPromise = audioEl.play();
    if (playPromise !== undefined) {
      playPromise
        .then(() => {
          usingHtmlAudio = true;
          musicLabel.textContent = "Musik: ON";
          musicIcon.textContent = "🎵";
        })
        .catch(() => {
          // Fallback ke Web Audio Music Box jika assets/musik.mp3 tidak ada
          usingHtmlAudio = false;
          musicBox.start();
          musicLabel.textContent = "Music Box: ON";
          musicIcon.textContent = "🎶";
        });
    }
  } else {
    musicBox.start();
  }
}

document.getElementById("music-toggle").addEventListener("click", () => {
  const audioEl = document.getElementById("bg-audio");
  const musicLabel = document.getElementById("music-label");
  const musicIcon = document.getElementById("music-icon");

  if (usingHtmlAudio && audioEl) {
    if (audioEl.paused) {
      audioEl.play();
      musicLabel.textContent = "Musik: ON";
      musicIcon.textContent = "🎵";
    } else {
      audioEl.pause();
      musicLabel.textContent = "Musik: OFF";
      musicIcon.textContent = "🔇";
    }
  } else {
    const active = musicBox.toggle();
    musicLabel.textContent = active ? "Music Box: ON" : "Musik: OFF";
    musicIcon.textContent = active ? "🎶" : "🔇";
  }
});

