function initTypewriter() {
  const target = document.getElementById("typewriter-text");
  let lineIdx = 0;
  let charIdx = 0;
  let isDeleting = false;

  function typeLoop() {
    const currentLine = CONFIG.typewriterLines[lineIdx];
    if (isDeleting) {
      charIdx--;
      target.textContent = currentLine.substring(0, charIdx);
    } else {
      charIdx++;
      target.textContent = currentLine.substring(0, charIdx);
    }

    let speed = isDeleting ? 30 : 60;

    if (!isDeleting && charIdx === currentLine.length) {
      speed = 2400;
      isDeleting = true;
    } else if (isDeleting && charIdx === 0) {
      isDeleting = false;
      lineIdx = (lineIdx + 1) % CONFIG.typewriterLines.length;
      speed = 400;
    }

    setTimeout(typeLoop, speed);
  }

  typeLoop();
}

